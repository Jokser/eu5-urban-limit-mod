# Urban Limit Reworked - regenerate in_game/common/location_ranks/00_default.txt from the CURRENT vanilla file.
# Run after every game patch:  powershell -ExecutionPolicy Bypass -File tools\regen_location_ranks.ps1
# The vanilla file is copied as is; only the city and town `allow` blocks get our delta, inserted right after
# `modifier:cannot_upgrade_location = no`:
#   - the province cap (gate 1): custom_tooltip urban_tt_<rank>_gate1_cap + can_upgrade_to_<rank>_under_province_cap
#   - the geography rule: tools\snippets\allow_snippet_<rank>.txt (trigger_if chain on climate, one tooltip line per
#     climate - the rank-upgrade UI cannot show nested OR/AND).
# Aborts without writing if an anchor is not found (vanilla changed - re-check the generator).
$ErrorActionPreference = 'Stop'
$tools = Split-Path -Parent $MyInvocation.MyCommand.Path
$mod   = Split-Path -Parent $tools
$game  = 'c:\Program Files (x86)\Steam\steamapps\common\Europa Universalis V\game'
$utf8bom = New-Object System.Text.UTF8Encoding($true)

$src = Join-Path $game 'in_game\common\location_ranks\00_default.txt'
$dst = Join-Path $mod  'in_game\common\location_ranks\00_default.txt'
$t = [IO.File]::ReadAllText($src)
foreach ($rk in @('city', 'town')) {
    $snip = [IO.File]::ReadAllText((Join-Path $tools "snippets\allow_snippet_$rk.txt")).Replace("`r`n", "`n")
    $ins  = "`t`tcustom_tooltip = {`n`t`t`ttext = urban_tt_${rk}_gate1_cap`n`t`t`tcan_upgrade_to_${rk}_under_province_cap = yes`n`t`t}`n" +
            "`t`t# Urban Limit Reworked: per-climate geography rule, one tooltip line for the location's climate`n" + $snip
    $rx = "(?s)(\n$rk = \{.*?\n\tallow = \{[^\n]*\n(?:(?!\n\t\}).)*?\t\tmodifier:cannot_upgrade_location = no\r?\n)"
    if ($t -notmatch $rx) { throw "anchor for '$rk' allow not found in vanilla - location_ranks NOT written; re-check the generator" }
    $t = ([regex]$rx).Replace($t, { param($m) $m.Groups[1].Value + $ins }, 1)
}
$t = "# GENERATED by Urban Limit Reworked\tools\regen_location_ranks.ps1 from vanilla + the urban allow delta. Do not edit here.`n" + $t.TrimStart([char]0xFEFF)
[IO.File]::WriteAllText($dst, $t, $utf8bom)
Write-Host "ok  generated $dst"
